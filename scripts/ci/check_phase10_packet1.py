"""Fail when Phase 10 Packet 1 tests collect zero cases or IaC policy fails."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from smart_rag_core.release.phase10_packet1 import (
    Phase10Packet1GateError,
    evaluate_packet1,
    write_packet1_artifacts,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
MANDATORY_TESTS = (
    "tests/unit/test_phase10_packet1.py",
    "tests/contract/test_phase10_packet1.py",
)


def _junit_counts(report: Path) -> tuple[int, int, int, int]:
    """Read test/failure/error/skip totals from a pytest JUnit report.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, failures, errors, skipped)`` totals.

    Raises:
        Phase10Packet1GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet1GateError("Packet 1 pytest report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    if not suites:
        raise Phase10Packet1GateError("Packet 1 pytest report contains no test suite")

    def total(attribute: str) -> int:
        """Sum one integer JUnit attribute across suites.

        Args:
            attribute: JUnit attribute name.

        Returns:
            Integer total.
        """

        return sum(int(suite.attrib.get(attribute, "0") or 0) for suite in suites)

    return (
        total("tests"),
        total("failures"),
        total("errors"),
        total("skipped"),
    )


def main() -> int:
    """Run Packet 1 tests, classify evidence, and reject zero collection.

    Returns:
        ``0`` when tests were collected, none failed, and IaC policy Passed.
        Live AWS apply remaining Blocked is not a gate failure.

    Raises:
        Phase10Packet1GateError: On zero collection, test failure, or IaC fail.
    """

    with tempfile.TemporaryDirectory(prefix="smart-rag-phase10-") as directory:
        report = Path(directory) / "junit.xml"
        completed = subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "--junitxml",
                str(report),
                *MANDATORY_TESTS,
            ],
            cwd=REPO_ROOT,
            check=False,
        )
        tests, failures, errors, skipped = _junit_counts(report)
    print(
        "phase10_packet1_tests "
        f"tests={tests} failures={failures} errors={errors} skipped={skipped}"
    )
    if tests == 0:
        raise Phase10Packet1GateError("Phase 10 Packet 1 suite collected zero tests")
    if completed.returncode != 0 or failures or errors:
        raise Phase10Packet1GateError("Phase 10 Packet 1 suite failed")
    policy, live, rows = evaluate_packet1(REPO_ROOT)
    write_packet1_artifacts(REPO_ROOT, policy=policy, live=live, rows=rows)
    print(f"phase10_packet1_iac passed={policy.passed} sha256={policy.iac_sha256}")
    print(f"phase10_packet1_live apply_state={live.apply_state}")
    for row in rows:
        print(f"{row.check} {row.classification}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Phase10Packet1GateError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
