"""Fail when Phase 10 Packet 6 tests collect zero cases or policy fails."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections.abc import Sequence
from pathlib import Path

from smart_rag_core.release.phase10_constants import (
    PACKET6_RESTORE_INCOMPLETE_TEST_FILES,
)
from smart_rag_core.release.phase10_packet6 import (
    Phase10Packet6GateError,
    evaluate_packet6,
    write_packet6_artifacts,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
MANDATORY_TESTS = (
    "tests/unit/test_phase10_packet6.py",
    "tests/contract/test_phase10_packet6.py",
    *PACKET6_RESTORE_INCOMPLETE_TEST_FILES,
)


def _junit_counts(report: Path) -> tuple[int, int, int, int]:
    """Read test/failure/error/skip totals from a pytest JUnit report.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, failures, errors, skipped)`` totals.

    Raises:
        Phase10Packet6GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet6GateError("Packet 6 pytest report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    if not suites:
        raise Phase10Packet6GateError("Packet 6 pytest report contains no test suite")

    def total(attribute: str) -> int:
        """Sum one integer JUnit attribute across suites.

        Args:
            attribute: JUnit attribute name.

        Returns:
            Integer total.
        """

        return sum(int(suite.attrib.get(attribute, "0") or 0) for suite in suites)

    return (
        total("tests"),
        total("failures"),
        total("errors"),
        total("skipped"),
    )


def _subset_needles(specs: Sequence[str]) -> tuple[str, ...]:
    """Return JUnit match tokens for pytest file or nodeid specs.

    Args:
        specs: Pytest paths, optionally with ``::`` nodeids.

    Returns:
        Tokens matched against classname, name, and file attributes.
    """

    needles: list[str] = []
    for spec in specs:
        if "::" in spec:
            needles.append(spec.rsplit("::", 1)[-1])
        else:
            needles.append(Path(spec).stem)
    return tuple(needles)


def _subset_counts(report: Path, specs: Sequence[str]) -> tuple[int, int]:
    """Count matching testcases and skips from JUnit XML.

    Args:
        report: JUnit XML path generated by pytest.
        specs: Pytest file or nodeid specs.

    Returns:
        ``(tests, skipped)`` for the subset.

    Raises:
        Phase10Packet6GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet6GateError("Packet 6 subset report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    needles = _subset_needles(specs)
    tests = 0
    skipped = 0
    for suite in suites:
        for case in suite.findall("testcase"):
            blob = (
                f"{case.attrib.get('classname', '')} "
                f"{case.attrib.get('name', '')} "
                f"{case.attrib.get('file', '')}"
            )
            if not any(needle in blob for needle in needles):
                continue
            tests += 1
            if case.find("skipped") is not None:
                skipped += 1
    return tests, skipped


def main() -> int:
    """Run Packet 6 tests, classify evidence, and reject zero collection.

    Returns:
        ``0`` when Packet 6 tests were collected, none failed, policy
        Passed, and classifications were written. Live PITR/EC2/drain
        remaining Blocked is not a gate failure. Packets 1-5 remaining
        unchecked is not a gate failure.

    Raises:
        Phase10Packet6GateError: On zero collection, test failure, or
            policy fail.
    """

    with tempfile.TemporaryDirectory(prefix="smart-rag-phase10-p6-") as directory:
        report = Path(directory) / "junit.xml"
        completed = subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "--junitxml",
                str(report),
                *MANDATORY_TESTS,
            ],
            cwd=REPO_ROOT,
            check=False,
        )
        tests, failures, errors, skipped = _junit_counts(report)
        restore_tests, restore_skipped = _subset_counts(
            report, PACKET6_RESTORE_INCOMPLETE_TEST_FILES
        )
    print(
        "phase10_packet6_tests "
        f"tests={tests} failures={failures} errors={errors} skipped={skipped}"
    )
    print(
        "phase10_packet6_restore_incomplete_subset "
        f"tests={restore_tests} skipped={restore_skipped}"
    )
    if tests == 0:
        raise Phase10Packet6GateError("Phase 10 Packet 6 suite collected zero tests")
    if completed.returncode != 0 or failures or errors:
        raise Phase10Packet6GateError("Phase 10 Packet 6 suite failed")
    restore_ok = restore_tests > 0 and restore_skipped == 0
    policy, live, restore, rebuild, smoke, contraction_absent, rows = evaluate_packet6(
        REPO_ROOT,
        restore_incomplete_ok=restore_ok,
    )
    write_packet6_artifacts(
        REPO_ROOT,
        policy=policy,
        live=live,
        rows=rows,
        restore=restore,
        rebuild=rebuild,
        smoke=smoke,
        contraction_absent=contraction_absent,
        restore_incomplete_subset={
            "tests": restore_tests,
            "skipped": restore_skipped,
            "files": list(PACKET6_RESTORE_INCOMPLETE_TEST_FILES),
        },
    )
    print(f"phase10_packet6_policy passed={policy.passed} sha256={policy.iac_sha256}")
    print(f"phase10_packet6_live pitr_ec2_drain={live.apply_state}")
    for row in rows:
        print(f"{row.check} {row.classification}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Phase10Packet6GateError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
