"""Fail when Phase 10 Packet 3 tests collect zero cases or policy fails."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from smart_rag_core.release.phase10_constants import PACKET3_CRAWL_TEST_FILES
from smart_rag_core.release.phase10_packet3 import (
    Phase10Packet3GateError,
    evaluate_packet3,
    write_packet3_artifacts,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
MANDATORY_TESTS = (
    "tests/unit/test_phase10_packet3.py",
    "tests/contract/test_phase10_packet3.py",
    *PACKET3_CRAWL_TEST_FILES,
)


def _junit_counts(report: Path) -> tuple[int, int, int, int]:
    """Read test/failure/error/skip totals from a pytest JUnit report.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, failures, errors, skipped)`` totals.

    Raises:
        Phase10Packet3GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet3GateError("Packet 3 pytest report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    if not suites:
        raise Phase10Packet3GateError("Packet 3 pytest report contains no test suite")

    def total(attribute: str) -> int:
        """Sum one integer JUnit attribute across suites.

        Args:
            attribute: JUnit attribute name.

        Returns:
            Integer total.
        """

        return sum(int(suite.attrib.get(attribute, "0") or 0) for suite in suites)

    return (
        total("tests"),
        total("failures"),
        total("errors"),
        total("skipped"),
    )


def _crawl_subset_counts(report: Path) -> tuple[int, int]:
    """Count crawl-policy/ssrf testcases and skips from JUnit XML.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, skipped)`` for the Packet 3 crawl subset.

    Raises:
        Phase10Packet3GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet3GateError(
            "Packet 3 crawl subset report is unavailable"
        ) from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    tests = 0
    skipped = 0
    for suite in suites:
        for case in suite.findall("testcase"):
            classname = case.attrib.get("classname", "")
            file_name = case.attrib.get("file", "")
            blob = f"{classname} {file_name}"
            if "test_crawl_policy" not in blob and "test_crawl_ssrf" not in blob:
                continue
            tests += 1
            if case.find("skipped") is not None:
                skipped += 1
    return tests, skipped


def main() -> int:
    """Run Packet 3 tests, classify evidence, and reject zero collection.

    Returns:
        ``0`` when tests were collected, none failed, crawl subset is
        nonzero without skip, and Packet 3 policy Passed. Live CDN/scan/alert
        remaining Blocked is not a gate failure.

    Raises:
        Phase10Packet3GateError: On zero collection, skip, test failure, or
            policy fail.
    """

    with tempfile.TemporaryDirectory(prefix="smart-rag-phase10-p3-") as directory:
        report = Path(directory) / "junit.xml"
        completed = subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "--junitxml",
                str(report),
                *MANDATORY_TESTS,
            ],
            cwd=REPO_ROOT,
            check=False,
        )
        tests, failures, errors, skipped = _junit_counts(report)
        crawl_tests, crawl_skipped = _crawl_subset_counts(report)
    print(
        "phase10_packet3_tests "
        f"tests={tests} failures={failures} errors={errors} skipped={skipped}"
    )
    print(f"phase10_packet3_crawl_subset tests={crawl_tests} skipped={crawl_skipped}")
    if tests == 0:
        raise Phase10Packet3GateError("Phase 10 Packet 3 suite collected zero tests")
    if completed.returncode != 0 or failures or errors:
        raise Phase10Packet3GateError("Phase 10 Packet 3 suite failed")
    if crawl_tests == 0 or crawl_skipped:
        raise Phase10Packet3GateError(
            "Phase 10 Packet 3 crawl-policy/ssrf subset collected zero tests or skipped"
        )
    crawl_subset = {
        "tests": crawl_tests,
        "skipped": crawl_skipped,
        "files": list(PACKET3_CRAWL_TEST_FILES),
    }
    policy, live, rows = evaluate_packet3(REPO_ROOT, crawl_subset_ok=True)
    write_packet3_artifacts(
        REPO_ROOT,
        policy=policy,
        live=live,
        rows=rows,
        crawl_subset=crawl_subset,
    )
    print(f"phase10_packet3_iac passed={policy.passed} sha256={policy.iac_sha256}")
    print(f"phase10_packet3_live cdn_scan_alert={live.apply_state}")
    for row in rows:
        print(f"{row.check} {row.classification}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Phase10Packet3GateError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
