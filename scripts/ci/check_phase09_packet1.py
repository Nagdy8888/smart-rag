"""Fail when Phase 9 Packet 1 candidate tests collect zero cases."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
MANDATORY_TESTS = (
    "tests/unit/test_phase09_candidate.py",
    "tests/contract/test_phase09_candidate.py",
)


class Phase09Packet1GateError(RuntimeError):
    """Raised when Packet 1 candidate tests are missing or failed."""


def _junit_counts(report: Path) -> tuple[int, int, int, int]:
    """Read test/failure/error/skip totals from a pytest JUnit report.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, failures, errors, skipped)`` totals.

    Raises:
        Phase09Packet1GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase09Packet1GateError("Packet 1 pytest report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    if not suites:
        raise Phase09Packet1GateError("Packet 1 pytest report contains no test suite")

    def total(attribute: str) -> int:
        """Sum one integer JUnit attribute across suites."""

        return sum(int(suite.attrib.get(attribute, "0") or 0) for suite in suites)

    return (
        total("tests"),
        total("failures"),
        total("errors"),
        total("skipped"),
    )


def main() -> int:
    """Run Packet 1 unit and contract tests and reject zero collection.

    Returns:
        ``0`` when tests were collected and none failed. Skips are allowed
        unless ``SMART_RAG_REQUIRE_PHASE09_CANDIDATE=1``.
    """

    with tempfile.TemporaryDirectory(prefix="smart-rag-phase09-") as directory:
        report = Path(directory) / "junit.xml"
        completed = subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "--junitxml",
                str(report),
                *MANDATORY_TESTS,
            ],
            cwd=REPO_ROOT,
            check=False,
        )
        tests, failures, errors, skipped = _junit_counts(report)
    print(
        "phase09_packet1_tests "
        f"tests={tests} failures={failures} errors={errors} skipped={skipped}"
    )
    if tests == 0:
        raise Phase09Packet1GateError("Phase 9 Packet 1 suite collected zero tests")
    if completed.returncode != 0 or failures or errors:
        raise Phase09Packet1GateError("Phase 9 Packet 1 suite failed")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Phase09Packet1GateError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
