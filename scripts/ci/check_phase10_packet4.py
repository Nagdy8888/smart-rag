"""Fail when Phase 10 Packet 4 tests collect zero cases or origin policy fails."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections.abc import Sequence
from pathlib import Path

from smart_rag_core.release.phase10_constants import (
    PACKET4_JWKS_TEST_FILES,
    PACKET4_PARADEDB_TEST_FILES,
    PACKET4_SSE_SUPPORT_TEST_FILES,
    PACKET4_VALKEY_TEST_FILES,
)
from smart_rag_core.release.phase10_packet4 import (
    Phase10Packet4GateError,
    evaluate_packet4,
    write_packet4_artifacts,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
MANDATORY_TESTS = (
    "tests/unit/test_phase10_packet4.py",
    "tests/contract/test_phase10_packet4.py",
    *PACKET4_JWKS_TEST_FILES,
    *PACKET4_PARADEDB_TEST_FILES,
    *PACKET4_VALKEY_TEST_FILES,
    *PACKET4_SSE_SUPPORT_TEST_FILES,
)


def _junit_counts(report: Path) -> tuple[int, int, int, int]:
    """Read test/failure/error/skip totals from a pytest JUnit report.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, failures, errors, skipped)`` totals.

    Raises:
        Phase10Packet4GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet4GateError("Packet 4 pytest report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    if not suites:
        raise Phase10Packet4GateError("Packet 4 pytest report contains no test suite")

    def total(attribute: str) -> int:
        """Sum one integer JUnit attribute across suites.

        Args:
            attribute: JUnit attribute name.

        Returns:
            Integer total.
        """

        return sum(int(suite.attrib.get(attribute, "0") or 0) for suite in suites)

    return (
        total("tests"),
        total("failures"),
        total("errors"),
        total("skipped"),
    )


def _subset_needles(specs: Sequence[str]) -> tuple[str, ...]:
    """Return JUnit match tokens for pytest file or nodeid specs.

    Args:
        specs: Pytest paths, optionally with ``::`` nodeids.

    Returns:
        Tokens matched against classname, name, and file attributes.
    """

    needles: list[str] = []
    for spec in specs:
        if "::" in spec:
            needles.append(spec.rsplit("::", 1)[-1])
        else:
            needles.append(Path(spec).stem)
    return tuple(needles)


def _subset_counts(report: Path, specs: Sequence[str]) -> tuple[int, int]:
    """Count matching testcases and skips from JUnit XML.

    Args:
        report: JUnit XML path generated by pytest.
        specs: Pytest file or nodeid specs.

    Returns:
        ``(tests, skipped)`` for the subset.

    Raises:
        Phase10Packet4GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet4GateError("Packet 4 subset report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    needles = _subset_needles(specs)
    tests = 0
    skipped = 0
    for suite in suites:
        for case in suite.findall("testcase"):
            blob = (
                f"{case.attrib.get('classname', '')} "
                f"{case.attrib.get('name', '')} "
                f"{case.attrib.get('file', '')}"
            )
            if not any(needle in blob for needle in needles):
                continue
            tests += 1
            if case.find("skipped") is not None:
                skipped += 1
    return tests, skipped


def main() -> int:
    """Run Packet 4 tests, classify evidence, and reject zero collection.

    Returns:
        ``0`` when Packet 4 tests were collected, none failed, origin policy
        Passed, and classifications were written. Live CDN SSE remaining
        Blocked is not a gate failure. Packets 1-3 remaining unchecked is
        not a gate failure. Application JWKS tests collecting zero cases
        classify P10-04-A Blocked instead of skipping the row.

    Raises:
        Phase10Packet4GateError: On zero Packet 4 collection, test failure, or
            origin policy fail.
    """

    with tempfile.TemporaryDirectory(prefix="smart-rag-phase10-p4-") as directory:
        report = Path(directory) / "junit.xml"
        completed = subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "--junitxml",
                str(report),
                *MANDATORY_TESTS,
            ],
            cwd=REPO_ROOT,
            check=False,
        )
        tests, failures, errors, skipped = _junit_counts(report)
        jwks_tests, jwks_skipped = _subset_counts(report, PACKET4_JWKS_TEST_FILES)
        parade_tests, parade_skipped = _subset_counts(
            report, PACKET4_PARADEDB_TEST_FILES
        )
        valkey_tests, valkey_skipped = _subset_counts(report, PACKET4_VALKEY_TEST_FILES)
        sse_tests, sse_skipped = _subset_counts(report, PACKET4_SSE_SUPPORT_TEST_FILES)
    print(
        "phase10_packet4_tests "
        f"tests={tests} failures={failures} errors={errors} skipped={skipped}"
    )
    print(f"phase10_packet4_jwks_subset tests={jwks_tests} skipped={jwks_skipped}")
    print(
        f"phase10_packet4_paradedb_subset tests={parade_tests} skipped={parade_skipped}"
    )
    print(
        f"phase10_packet4_valkey_subset tests={valkey_tests} skipped={valkey_skipped}"
    )
    print(f"phase10_packet4_sse_support tests={sse_tests} skipped={sse_skipped}")
    if tests == 0:
        raise Phase10Packet4GateError("Phase 10 Packet 4 suite collected zero tests")
    if completed.returncode != 0 or failures or errors:
        raise Phase10Packet4GateError("Phase 10 Packet 4 suite failed")
    jwks_ok = jwks_tests > 0 and jwks_skipped == 0
    parade_ok = parade_tests > 0 and parade_skipped == 0
    valkey_ok = valkey_tests > 0 and valkey_skipped == 0
    if not parade_ok:
        raise Phase10Packet4GateError(
            "Phase 10 Packet 4 ParadeDB degrade subset collected zero tests or skipped"
        )
    if not valkey_ok:
        raise Phase10Packet4GateError(
            "Phase 10 Packet 4 Valkey subset collected zero tests or skipped"
        )
    jwks_subset = {
        "tests": jwks_tests,
        "skipped": jwks_skipped,
        "files": list(PACKET4_JWKS_TEST_FILES),
    }
    paradedb_subset = {
        "tests": parade_tests,
        "skipped": parade_skipped,
        "files": list(PACKET4_PARADEDB_TEST_FILES),
    }
    valkey_subset = {
        "tests": valkey_tests,
        "skipped": valkey_skipped,
        "files": list(PACKET4_VALKEY_TEST_FILES),
    }
    sse_support = {
        "tests": sse_tests,
        "skipped": sse_skipped,
        "files": list(PACKET4_SSE_SUPPORT_TEST_FILES),
        "cdn_pass": False,
    }
    policy, live, rows, degrade = evaluate_packet4(
        REPO_ROOT,
        jwks_subset_ok=jwks_ok,
        paradedb_subset_ok=parade_ok,
        valkey_subset_ok=valkey_ok,
    )
    write_packet4_artifacts(
        REPO_ROOT,
        policy=policy,
        live=live,
        rows=rows,
        degrade=degrade,
        jwks_subset=jwks_subset,
        paradedb_subset=paradedb_subset,
        valkey_subset=valkey_subset,
        sse_support=sse_support,
    )
    print(f"phase10_packet4_origin passed={policy.passed} sha256={policy.iac_sha256}")
    print(f"phase10_packet4_live rotation_stream_kill={live.apply_state}")
    for row in rows:
        print(f"{row.check} {row.classification}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Phase10Packet4GateError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
