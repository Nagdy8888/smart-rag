"""Fail when Phase 10 Packet 5 tests collect zero cases or policy fails."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections.abc import Sequence
from pathlib import Path

from smart_rag_core.release.phase10_constants import (
    PACKET5_AUDIT_TEST_FILES,
    PACKET5_BUDGET_TEST_FILES,
    PACKET5_CORS_TEST_FILES,
    PACKET5_OAUTH_TEST_FILES,
    PACKET5_PAUSE_TEST_FILES,
)
from smart_rag_core.release.phase10_packet5 import (
    Phase10Packet5GateError,
    evaluate_packet5,
    write_packet5_artifacts,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
MANDATORY_TESTS = (
    "tests/unit/test_phase10_packet5.py",
    "tests/contract/test_phase10_packet5.py",
    *PACKET5_AUDIT_TEST_FILES,
    *PACKET5_PAUSE_TEST_FILES,
    *PACKET5_BUDGET_TEST_FILES,
    *PACKET5_OAUTH_TEST_FILES,
    *PACKET5_CORS_TEST_FILES,
)


def _junit_counts(report: Path) -> tuple[int, int, int, int]:
    """Read test/failure/error/skip totals from a pytest JUnit report.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, failures, errors, skipped)`` totals.

    Raises:
        Phase10Packet5GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet5GateError("Packet 5 pytest report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    if not suites:
        raise Phase10Packet5GateError("Packet 5 pytest report contains no test suite")

    def total(attribute: str) -> int:
        """Sum one integer JUnit attribute across suites.

        Args:
            attribute: JUnit attribute name.

        Returns:
            Integer total.
        """

        return sum(int(suite.attrib.get(attribute, "0") or 0) for suite in suites)

    return (
        total("tests"),
        total("failures"),
        total("errors"),
        total("skipped"),
    )


def _subset_needles(specs: Sequence[str]) -> tuple[str, ...]:
    """Return JUnit match tokens for pytest file or nodeid specs.

    Args:
        specs: Pytest paths, optionally with ``::`` nodeids.

    Returns:
        Tokens matched against classname, name, and file attributes.
    """

    needles: list[str] = []
    for spec in specs:
        if "::" in spec:
            needles.append(spec.rsplit("::", 1)[-1])
        else:
            needles.append(Path(spec).stem)
    return tuple(needles)


def _subset_counts(report: Path, specs: Sequence[str]) -> tuple[int, int]:
    """Count matching testcases and skips from JUnit XML.

    Args:
        report: JUnit XML path generated by pytest.
        specs: Pytest file or nodeid specs.

    Returns:
        ``(tests, skipped)`` for the subset.

    Raises:
        Phase10Packet5GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet5GateError("Packet 5 subset report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    needles = _subset_needles(specs)
    tests = 0
    skipped = 0
    for suite in suites:
        for case in suite.findall("testcase"):
            blob = (
                f"{case.attrib.get('classname', '')} "
                f"{case.attrib.get('name', '')} "
                f"{case.attrib.get('file', '')}"
            )
            if not any(needle in blob for needle in needles):
                continue
            tests += 1
            if case.find("skipped") is not None:
                skipped += 1
    return tests, skipped


def main() -> int:
    """Run Packet 5 tests, classify evidence, and reject zero collection.

    Returns:
        ``0`` when Packet 5 tests were collected, none failed, policy
        Passed, and classifications were written. Live KMS/SNS/SES/pool
        remaining Blocked is not a gate failure. Packets 1-4 remaining
        unchecked is not a gate failure.

    Raises:
        Phase10Packet5GateError: On zero collection, test failure, or
            policy fail.
    """

    with tempfile.TemporaryDirectory(prefix="smart-rag-phase10-p5-") as directory:
        report = Path(directory) / "junit.xml"
        completed = subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "--junitxml",
                str(report),
                *MANDATORY_TESTS,
            ],
            cwd=REPO_ROOT,
            check=False,
        )
        tests, failures, errors, skipped = _junit_counts(report)
        tamper_tests, tamper_skipped = _subset_counts(report, PACKET5_AUDIT_TEST_FILES)
        pause_tests, pause_skipped = _subset_counts(report, PACKET5_PAUSE_TEST_FILES)
        budget_tests, budget_skipped = _subset_counts(report, PACKET5_BUDGET_TEST_FILES)
        oauth_tests, oauth_skipped = _subset_counts(report, PACKET5_OAUTH_TEST_FILES)
        cors_tests, cors_skipped = _subset_counts(report, PACKET5_CORS_TEST_FILES)
    print(
        "phase10_packet5_tests "
        f"tests={tests} failures={failures} errors={errors} skipped={skipped}"
    )
    print(
        f"phase10_packet5_tamper_subset tests={tamper_tests} skipped={tamper_skipped}"
    )
    print(f"phase10_packet5_pause_subset tests={pause_tests} skipped={pause_skipped}")
    print(
        f"phase10_packet5_budget_subset tests={budget_tests} skipped={budget_skipped}"
    )
    print(f"phase10_packet5_oauth_support tests={oauth_tests} skipped={oauth_skipped}")
    print(f"phase10_packet5_cors_support tests={cors_tests} skipped={cors_skipped}")
    if tests == 0:
        raise Phase10Packet5GateError("Phase 10 Packet 5 suite collected zero tests")
    if completed.returncode != 0 or failures or errors:
        raise Phase10Packet5GateError("Phase 10 Packet 5 suite failed")
    tamper_ok = tamper_tests > 0 and tamper_skipped == 0
    pause_ok = pause_tests > 0 and pause_skipped == 0
    budget_ok = budget_tests > 0 and budget_skipped == 0
    policy, live, rows = evaluate_packet5(
        REPO_ROOT,
        tamper_subset_ok=tamper_ok,
        pause_ok=pause_ok,
        budget_ok=budget_ok,
    )
    write_packet5_artifacts(
        REPO_ROOT,
        policy=policy,
        live=live,
        rows=rows,
        tamper_subset={
            "tests": tamper_tests,
            "skipped": tamper_skipped,
            "files": list(PACKET5_AUDIT_TEST_FILES),
        },
        pause_subset={
            "tests": pause_tests,
            "skipped": pause_skipped,
            "files": list(PACKET5_PAUSE_TEST_FILES),
        },
        budget_subset={
            "tests": budget_tests,
            "skipped": budget_skipped,
            "files": list(PACKET5_BUDGET_TEST_FILES),
        },
        oauth_subset={
            "tests": oauth_tests,
            "skipped": oauth_skipped,
            "files": list(PACKET5_OAUTH_TEST_FILES),
        },
        cors_subset={
            "tests": cors_tests,
            "skipped": cors_skipped,
            "files": list(PACKET5_CORS_TEST_FILES),
        },
    )
    print(f"phase10_packet5_iac passed={policy.passed} sha256={policy.iac_sha256}")
    print(f"phase10_packet5_live kms_sns_ses_pool={live.apply_state}")
    for row in rows:
        print(f"{row.check} {row.classification}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Phase10Packet5GateError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
