"""Fail when Phase 10 Packet 7 tests collect zero cases or policy fails.

This gate consumes committed Packets 1-6 JSON. It does not re-run those
pytest suites, apply Terraform, or treat holdout as open.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from smart_rag_core.release.phase10_packet7 import (
    Phase10Packet7GateError,
    evaluate_packet7,
    write_packet7_artifacts,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
MANDATORY_TESTS = (
    "tests/unit/test_phase10_packet7.py",
    "tests/contract/test_phase10_packet7.py",
)


def _junit_counts(report: Path) -> tuple[int, int, int, int]:
    """Read test/failure/error/skip totals from a pytest JUnit report.

    Args:
        report: JUnit XML path generated by pytest.

    Returns:
        ``(tests, failures, errors, skipped)`` totals.

    Raises:
        Phase10Packet7GateError: If the report is missing or malformed.
    """

    try:
        root = ET.parse(report).getroot()  # noqa: S314 - local pytest output only.
    except (ET.ParseError, OSError) as exc:
        raise Phase10Packet7GateError("Packet 7 pytest report is unavailable") from exc
    suites = [root] if root.tag == "testsuite" else list(root.findall("testsuite"))
    if not suites:
        raise Phase10Packet7GateError("Packet 7 pytest report contains no test suite")

    def total(attribute: str) -> int:
        """Sum one integer JUnit attribute across suites.

        Args:
            attribute: JUnit attribute name.

        Returns:
            Integer total.
        """

        return sum(int(suite.attrib.get(attribute, "0") or 0) for suite in suites)

    return (
        total("tests"),
        total("failures"),
        total("errors"),
        total("skipped"),
    )


def main() -> int:
    """Run Packet 7 tests, classify evidence, and reject zero collection.

    Returns:
        ``0`` when Packet 7 tests were collected, none failed, custody
        policy Passed, and classifications were written. P10-07-A/C/D
        remaining Blocked is not a CI failure. Wrapper complete or a
        checked checkbox is a failure.

    Raises:
        Phase10Packet7GateError: On zero collection, test failure, or
            policy fail.
    """

    with tempfile.TemporaryDirectory(prefix="smart-rag-phase10-p7-") as directory:
        report = Path(directory) / "junit.xml"
        completed = subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "pytest",
                "-q",
                "--junitxml",
                str(report),
                *MANDATORY_TESTS,
            ],
            cwd=REPO_ROOT,
            check=False,
        )
        tests, failures, errors, skipped = _junit_counts(report)
    print(
        "phase10_packet7_tests "
        f"tests={tests} failures={failures} errors={errors} skipped={skipped}"
    )
    if tests == 0:
        raise Phase10Packet7GateError("Phase 10 Packet 7 suite collected zero tests")
    if completed.returncode != 0 or failures or errors or skipped:
        raise Phase10Packet7GateError("Phase 10 Packet 7 suite failed")
    policy, live, matrices, rows = evaluate_packet7(
        REPO_ROOT,
        packet7_tests_ok=True,
    )
    write_packet7_artifacts(
        REPO_ROOT,
        policy=policy,
        live=live,
        rows=rows,
        matrices=matrices,
        packet7_subset={
            "tests": tests,
            "skipped": skipped,
            "files": list(MANDATORY_TESTS),
        },
    )
    print(f"phase10_packet7_policy passed={policy.passed} sha256={policy.iac_sha256}")
    print(f"phase10_packet7_live oidc_assume={live.apply_state}")
    for row in rows:
        print(f"{row.check} {row.classification}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Phase10Packet7GateError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1) from exc
